<script>
  import { formatScore } from './format.js';
  import LineCrop from './LineCrop.svelte';

  let {
    /** @type {import('./types.js').AlignResult} */
    row,
    /** @type {number} */
    threshold = 70,
    /** @type {import('./types.js').LineCropView | null} */
    crop = null,
    /** @type {(row: import('./types.js').AlignResult, value: string) => void} */
    onEdit = () => {},
  } = $props();

  const flagged = $derived(Number(row?.score ?? NaN) < Number(threshold));
</script>

<li class="row" class:flagged>
  <div class="row-head">
    <span class="line-no">Line {row?.line_no ?? '—'}</span>
    <span class="score" class:low={flagged}>{formatScore(row?.score)}</span>
    {#if flagged}
      <span class="flag">Below threshold</span>
    {/if}
  </div>

  {#if crop !== null}
    <div class="cell">
      <span class="cell-label">Line image</span>
      <LineCrop {crop} />
    </div>
  {/if}

  <div class="cell">
    <span class="cell-label">OCR</span>
    <p class="hebrew" translate="no">{row?.ocr ?? ''}</p>
  </div>

  <div class="cell">
    <span class="cell-label">Diff</span>
    <!-- diff_html is generated by the server and only wraps characters in span.ocr-only / span.ref-only -->
    <p class="hebrew" translate="no">{@html row?.diff_html ?? ''}</p>
  </div>

  <div class="cell">
    <span class="cell-label">Reference</span>
    <p class="hebrew" translate="no">{row?.match ?? ''}</p>
  </div>

  <label class="cell">
    <span class="cell-label">Final match</span>
    <input
      class="hebrew edit"
      value={row?.final_match ?? ''}
      aria-label={`Final match for line ${row?.line_no ?? ''}`}
      oninput={(event) => onEdit(row, event.currentTarget.value)}
    />
  </label>
</li>
